"""Full audit of Rev D against Rev-C1: every part and net difference must be explained by a register ID.
usage: audit_changes.py <rev_c1.xml> <rev_d.xml> <out.md>      exit 1 if anything is unexplained"""
import sys, re, collections
sys.path.insert(0, __import__('os').path.dirname(__file__))
from netdiff import load
a, b, out = sys.argv[1:4]
ca, na = load(a); cb, nb = load(b)
na = {('+12V' if k == '+24V' else k): v for k, v in na.items()}   # the main rail was only renamed (A4)
def rng(p, lo, hi): return [f'{p}{i}' for i in range(lo, hi + 1)]
ID = {}
def tag(i, refs):
    for r in refs: ID[r] = i
tag('A1', ['U3', 'Q3', 'Q8', 'R21', 'C15', 'TP50', 'TP51', 'TP52', 'Q9', 'Q10', 'R78', 'D56'] + rng('R', 72, 77))
tag('A2', ['U5', 'U6', 'U7', 'U8', 'J19', 'J20', 'J24', 'SW1', 'SW2', 'D36', 'D37', 'D38', 'D40', 'FB1', 'D57', 'TP27', 'TP28', 'TP29', 'C37', 'C38', 'C39', 'C40', 'C42', 'C43', 'R52', 'R53'] + rng('R', 43, 50))
tag('B1', ['D19', 'D15', 'D27', 'D30', 'D33', 'D48'])                       # TVS 30 V -> 16 V
tag('B2', ['D50', 'D51', 'D52', 'D53', 'D54', 'D55', 'D1', 'D2', 'D10', 'D44', 'D6', 'D24', 'D4', 'D9', 'D35', 'D42'])  # same-part source swaps
tag('B3', ['D14', 'D26', 'D29', 'D32', 'D47', 'D49'])                         # SS54 -> SS34
tag('B4', ['Q1', 'Q2', 'Q4', 'Q5', 'Q6', 'Q7'])                               # Si2318 -> AO3400A
tag('B5', ['D13', 'D21', 'D22', 'D25', 'D28', 'D31', 'D39', 'D46'])           # LED colour
tag('B6', ['D18'])
tag('C1', ['C3', 'C24', 'C18', 'C52', 'C53', 'C55', 'C56'])                   # 2.2 nF / 470 pF
tag('C2', ['C11', 'C12', 'C13', 'C14', 'C22', 'C46', 'C49'])                  # 10 uF 1210 -> 1206
tag('C3', ['C21', 'C23', 'C57'])                                              # e-caps
tag('C4', ['R23', 'R25', 'R26', 'R27', 'U10'])
tag('A4', [])
tag('D2', ['J1', 'J6', 'J28', 'J29'])                                       # 2x3 headers -> 2 x 3-pin terminals each
tag('D1', ['J3', 'J4', 'J5', 'J9', 'J10', 'J11', 'J18', 'J21', 'J22', 'J23'])  # connectors
rows = collections.defaultdict(list)
unexpl = []
for r in sorted(set(ca) | set(cb), key=lambda s: (re.sub(r'\d+', '', s), int(re.sub(r'\D', '', s) or 0))):
    if r in ca and r in cb and ca[r] == cb[r]: continue
    if r not in ID: unexpl.append(r); continue
    kind = 'removed' if r not in cb else 'added' if r not in ca else 'changed'
    o, n = ca.get(r), cb.get(r)
    sig = (ID[r], kind, f"{o['value']} / {o['lcsc']} / {o['fp']}" if o else '-', f"{n['value']} / {n['lcsc']} / {n['fp']}" if n else '-')
    rows[sig].append(r)
touched = {r for r in ID}
netunexpl = []
for n in sorted(set(na) | set(nb)):
    pa, pb = na.get(n, set()), nb.get(n, set())
    diff = pa ^ pb
    if diff and not all(p[0] in touched or p[0] in ID for p in diff):
        # pin changes on parts that are not in the register list
        bad = sorted(p for p in diff if p[0] not in ID)
        netunexpl.append((n, bad))
same = sum(1 for r in ca if r in cb and ca[r] == cb[r])
with open(out, 'w') as f:
    f.write('# Rev D vs Rev-C1: complete part audit (generated by tools/audit_changes.py)\n\n')
    f.write(f'Rev-C1 parts: {len(ca)}; Rev D parts: {len(cb)}; identical (ref, value, LCSC, footprint): {same}; changed/added/removed: {sum(len(v) for v in rows.values())}; **unexplained: {len(unexpl)}**.\n\n')
    f.write('Register IDs refer to docs/CHANGE_REGISTER.md. Every difference below is mapped to an ID; the script exits non-zero if a differing part has no ID.\n\n')
    f.write('| ID | Kind | Refs | Rev-C1 (value / LCSC / footprint) | Rev D |\n|---|---|---|---|---|\n')
    for sig, refs in sorted(rows.items()):
        f.write(f'| {sig[0]} | {sig[1]} | {", ".join(refs)} | {sig[2]} | {sig[3]} |\n')
    f.write(f'\n## Nets\nNets in Rev-C1: {len(na)}; in Rev D: {len(nb)}. Net pin differences touching only register-listed parts: {sum(1 for n in set(na) | set(nb) if (na.get(n, set()) ^ nb.get(n, set())))}; net differences involving a part NOT in the register: **{len(netunexpl)}**.\n')
    for n, bad in netunexpl: f.write(f'- UNEXPLAINED net {n}: {bad}\n')
    f.write('\nNets whose pin set is identical in both revisions: ' + str(sum(1 for n in na if n in nb and na[n] == nb[n])) + '.\n')
print('unexplained parts:', unexpl, 'unexplained nets:', netunexpl)
sys.exit(1 if unexpl or netunexpl else 0)
